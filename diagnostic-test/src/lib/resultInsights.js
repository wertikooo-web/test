export function buildProfilePersonalSentence(profileType, answers = {}) {
  const tasks = answers.q4 ?? [];
  const barriers = answers.q11 ?? [];
  const expectations = answers.q12 ?? [];
  const useLevel = Number.isInteger(answers.q3) ? answers.q3 : 0;
  const aiStyle = Number.isInteger(answers.q10) ? answers.q10 : 0;

  const taskFocus = detectTaskFocus(tasks, expectations);
  const barrierFocus = detectBarrierFocus(barriers);

  if (profileType === 'Скептик') {
    return barrierFocus
      ? `Судя по ответам, вы пока подходите к AI осторожно: вам важно сначала разобраться, где он действительно полезен, и отдельно снять вопрос «${barrierFocus}».`
      : 'Судя по ответам, вы пока не спешите внедрять AI в работу: вам важны понятные, безопасные и практически проверенные примеры.';
  }

  if (profileType === 'Наблюдатель') {
    return taskFocus
      ? `По вашим ответам видно: интерес к AI уже есть, но пока он скорее точечный; логичная первая зона для пробы - ${taskFocus}.`
      : 'По вашим ответам видно: вы уже рядом с AI, но вам ещё нужен спокойный переход от знакомства к регулярному рабочему применению.';
  }

  if (profileType === 'Экспериментатор') {
    return taskFocus
      ? `Ваши ответы похожи на профиль человека, который уже пробует AI в деле и теперь может собрать это в понятную систему вокруг задачи: ${taskFocus}.`
      : 'Ваши ответы похожи на профиль человека, который уже пробует AI в деле, но пока использует его больше как набор отдельных удачных экспериментов.';
  }

  if (profileType === 'Практик') {
    return taskFocus
      ? `У вас уже есть рабочий контакт с AI: особенно заметен запрос использовать его не “вообще”, а для конкретной практической пользы - ${taskFocus}.`
      : 'У вас уже есть рабочий контакт с AI: следующий шаг - меньше разовых запросов и больше своих шаблонов, сценариев и повторяемых процессов.';
  }

  if (aiStyle >= 5 || useLevel >= 4) {
    return 'По ответам видно, что AI для вас уже не разовая подсказка, а часть рабочей системы: вам можно двигаться к собственным помощникам, автоматизациям и продуктовым решениям.';
  }

  return taskFocus
    ? `По ответам видно, что вы мыслите уже не отдельными запросами, а рабочими сценариями; сильнее всего это проявляется в теме: ${taskFocus}.`
    : 'По ответам видно, что вы мыслите уже не отдельными запросами, а рабочими сценариями, которые можно постепенно превращать в устойчивую AI-систему.';
}

export function buildPersonalizedProfileGuide(profileType, answers = {}) {
  const base = profileGuides[profileType] ?? profileGuides.Наблюдатель;
  const tasks = answers.q4 ?? [];
  const barriers = answers.q11 ?? [];
  const expectations = answers.q12 ?? [];
  const taskFocus = detectTaskFocus(tasks, expectations);
  const barrierFocus = detectBarrierFocus(barriers);
  const expectationFocus = detectExpectationFocus(expectations);
  const q3 = Number.isInteger(answers.q3) ? answers.q3 : 0;
  const q10 = Number.isInteger(answers.q10) ? answers.q10 : 0;
  const variant = answerVariant(answers);

  return {
    ...base,
    strength: buildStrengthText(profileType, { taskFocus, expectationFocus, q3, q10, variant }),
    nextStep: buildNextStepText(profileType, { taskFocus, barrierFocus, expectationFocus, q3, q10, variant }),
  };
}

