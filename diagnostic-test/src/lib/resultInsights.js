function detectTaskFocus(tasks, expectations) {
  const all = [...tasks, ...expectations].join(' ').toLowerCase();

  if (all.includes('документ') || all.includes('отчёт') || all.includes('характеристик')) {
    return 'документы, характеристики и отчёты';
  }
  if (all.includes('занят') || all.includes('упражнен') || all.includes('материал') || all.includes('карточ')) {
    return 'подготовка занятий, упражнений и материалов';
  }
  if (all.includes('клиент') || all.includes('родител') || all.includes('рекомендац')) {
    return 'понятная коммуникация с клиентами и родителями';
  }
  if (all.includes('книг') || all.includes('стат') || all.includes('методик')) {
    return 'анализ книг, статей и методик';
  }
  if (all.includes('презентац') || all.includes('визуаль') || all.includes('изображен')) {
    return 'визуальные материалы и презентации';
  }
  if (all.includes('gpt') || all.includes('помощник')) {
    return 'создание собственного AI-помощника';
  }

  return '';
}

function detectBarrierFocus(barriers) {
  const all = barriers.join(' ').toLowerCase();

  if (all.includes('времени')) return 'не хватает времени разобраться';
  if (all.includes('конфиденциаль')) return 'важна конфиденциальность данных';
  if (all.includes('качеств') || all.includes('ошиб')) return 'нужно понимать, как проверять ответы';
  if (all.includes('запрос')) return 'сложно формулировать запросы';
  if (all.includes('пример')) return 'нужны реальные примеры из практики';
  if (all.includes('начать')) return 'непонятно, с чего начать';

  return '';
}

function detectExpectationFocus(expectations) {
  const all = expectations.join(' ').toLowerCase();

  if (all.includes('возможности')) return 'понять реальные возможности AI без перегруза';
  if (all.includes('запрос') || all.includes('задач')) return 'научиться задавать AI более точные вопросы';
  if (all.includes('риски') || all.includes('ограничения')) return 'разобраться в рисках и границах безопасной работы';
  if (all.includes('экономить') || all.includes('время')) return 'экономить время на рутинных рабочих текстах';

  return '';
}

function answerVariant(answers = {}) {
  const text = JSON.stringify(answers);
  let hash = 0;
  for (let index = 0; index < text.length; index += 1) {
    hash = (hash * 31 + text.charCodeAt(index)) % 9973;
  }
  return hash;
}

function practiceVariantByFocus(focus, fallbackVariant) {
  if (!focus) return fallbackVariant;
  if (focus.includes('документ') || focus.includes('характеристик') || focus.includes('отчёт')) return 0;
  if (focus.includes('клиент') || focus.includes('родител')) return 1;
  if (focus.includes('занят') || focus.includes('упражнен') || focus.includes('материал')) return 2;
  return fallbackVariant;
}
